function cfg = paper_settings(model,noise_std,method)
%PAPER_SETTINGS Original numerical settings and full-resolution metric windows.
validateattributes(noise_std,{'numeric'},{'scalar','real','finite','positive'});
cfg=struct('dt',model.dt,'noise_std',noise_std,'history_stride',100, ...
 'half_N',model.half_N,'forced_samples',model.forced_samples, ...
 'response_acc_variance',model.response_acc_variance, ...
 'response_alpha',method.response_alpha,'damage_band_pp',1, ...
 'ode_rel_tol',1e-8,'ode_abs_d',1e-11,'ode_abs_v',1e-10, ...
 'ode_max_step',model.dt);
cfg.window_names={'full_record','healthy','early_post_damage', ...
 'settled_forced','free_decay','final_10_seconds'};
cfg.windows=[1 model.N;5001 model.half_N; ...
 model.half_N+1 model.half_N+5000;model.half_N+5001 model.forced_samples; ...
 model.forced_samples+1 model.N;model.N-10000 model.N];
end
