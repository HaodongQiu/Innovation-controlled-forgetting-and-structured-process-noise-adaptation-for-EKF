function spec = paper_case(model,case_id)
%PAPER_CASE Load a frozen random design; no method-dependent random draws.
validateattributes(case_id,{'numeric'},{'scalar','integer','>=',1,'<=',100});
root=fileparts(fileparts(mfilename('fullpath')));
data=load(fullfile(root,'data','cases',[model.id '_cases.mat']));
spec=struct('case_id',case_id,'true_k',data.true_k(:,case_id), ...
 'damaged_stories',double(data.damaged_stories(:,case_id)), ...
 'damage_pct',data.damage_pct(:,case_id), ...
 'case_seed',double(data.case_seed(case_id)), ...
 'noise_seed',double(data.noise_seed(case_id)));
assert(all(spec.damage_pct>=1 & spec.damage_pct<=20));
end
